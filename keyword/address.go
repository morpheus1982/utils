// ExtractAddress 从字符串中提取中国省市区信息
func ExtractAddress(text string) *Address {
	// 清理文本，去除多余空格和特殊字符
	text = strings.TrimSpace(text)
	if text == "" {
		return nil
	}

	// 初始化结果
	result := &Address{}

	// 提取省份信息
	result.Province = extractProvince(text)
	if result.Province == "" {
		return nil
	}

	// 提取城市信息
	result.City = extractCity(text, result.Province)

	// 提取区县信息
	result.District = extractDistrict(text, result.Province, result.City)

	return result
}

// extractProvince 从文本中提取省份信息
func extractProvince(text string) string {
	// 首先检查完整省份名称
	for _, full := range provinceMap {
		if strings.Contains(text, full) {
			return full
		}
	}

	// 然后检查较长简称
	for short, full := range provinceMap {
		if len(short) > 1 && strings.Contains(text, short) {
			return full
		}
	}

	// 最后检查简称（单字）
	for short, full := range provinceMap {
		if len(short) == 1 && strings.Contains(text, short) {
			// 确保这个单字是作为省份简称而不是普通字符
			// 例如，"北京市"中的"京"是简称，但"北京人"中的"京"不是
			if strings.Contains(text, full) || isProvinceInContext(text, short) {
				return full
			}
		}
	}

	return ""
}

// isProvinceInContext 判断单字简称是否在省份上下文中
func isProvinceInContext(text, short string) bool {
	// 创建正则表达式，匹配省份简称后可能跟的字符
	pattern := regexp.MustCompile(short + "[省市县区]")
	return pattern.MatchString(text)
}

// extractCity 从文本中提取城市信息
func extractCity(text, province string) string {
	// 对于直辖市，城市就是省份本身
	if province == "北京市" || province == "上海市" || province == "天津市" || province == "重庆市" {
		return province
	}

	// 获取省份对应的城市列表
	cities, exists := cityMap[province]
	if !exists {
		return ""
	}

	// 在文本中查找城市名称
	for _, city := range cities {
		if strings.Contains(text, city) {
			return city
		}
	}

	return ""
}

// extractDistrict 从文本中提取区县信息
func extractDistrict(text, province, city string) string {
	// 对于直辖市，直接使用城市名称查找区县
	if province == "北京市" || province == "上海市" || province == "天津市" || province == "重庆市" {
		districts, exists := cityDistrictMap[province]
		if !exists {
			return ""
		}

		for _, district := range districts {
			if strings.Contains(text, district) {
				return district
			}
		}
		return ""
	}

	// 对于非直辖市，使用城市名称查找区县
	if city == "" {
		return ""
	}

	// 尝试使用城市名（不带"市"后缀）查找区县
	districts, exists := cityDistrictMap[city]
	if !exists {
		// 如果找不到，尝试使用城市名+"市"查找区县
		districts, exists = cityDistrictMap[city+"市"]
		if !exists {
			return ""
		}
	}

	for _, district := range districts {
		if strings.Contains(text, district) {
			return district
		}
	}

	return ""
}
